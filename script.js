function buildPromises() {
  $("promiseBtn").onclick = e => {
    if (pIdx < CONFIG.promises.length) {
      const d = document.createElement("div");
      d.className = "promise"; d.textContent = CONFIG.promises[pIdx++];
      $("promises").appendChild(d);
      hearts(e.clientX, e.clientY, 8);
      if (pIdx >= CONFIG.promises.length) $("promiseBtn").textContent = "All of these, just for you 🤍";
    } else { centerBurst(20); }
  };
}

const audio = $("music");
function playMusic(silent) {
  audio.play().then(() => $("musicBtn").classList.add("on")).catch(() => {
    if (!silent) alert("Couldn't play the music. Check that the file in index.html matches your music file name 🎵");
  });
}
$("musicBtn").onclick = () => {
  if (audio.paused) playMusic(false);
  else { audio.pause(); $("musicBtn").classList.remove("on"); }
};

$("finalBtn").onclick = () => {
  $("final").classList.remove("hidden");
  $("finalStep1").classList.remove("hidden");
  $("finalStep2").classList.add("hidden");
  startFireworks(); confetti(80); vibrate([100, 50, 100]);
};
$("fYes").onclick = async () => {
  $("finalStep1").classList.add("hidden");
  $("finalStep2").classList.remove("hidden");
  confetti(150); centerBurst(40); vibrate([150, 60, 150, 60, 300]);
  const el = $("finalText");
  el.textContent = "";
  let skip = false;
  el.onclick = () => { skip = true; };
  for (const ch of CONFIG.finalLetter) {
    if (skip) { el.textContent = CONFIG.finalLetter; break; }
    el.textContent += ch;
    await wait(12);
  }
};
$("finalClose").onclick = () => { $("final").classList.add("hidden"); stopFireworks(); };