function boom(x, y) {
  const cols = ["#f3a9bb", "#d9c9f2", "#ffffff", "#d9a95b", "#ff7aa8"];
  for (let i = 0; i < 60; i++) {
    const a = rand(0, Math.PI * 2), s = rand(1, 6);
    parts.push({ x, y, vx: Math.cos(a) * s, vy: Math.sin(a) * s, life: 1, c: cols[i % cols.length] });
  }
}
function loop() {
  ctx.clearRect(0, 0, cv.width, cv.height);
  parts = parts.filter(p => p.life > 0);
  parts.forEach(p => {
    p.x += p.vx; p.y += p.vy; p.vy += .05; p.life -= .014;
    ctx.globalAlpha = Math.max(p.life, 0);
    ctx.fillStyle = p.c;
    ctx.beginPath(); ctx.arc(p.x, p.y, 3, 0, 7); ctx.fill();
  });
  requestAnimationFrame(loop);
}
loop();
