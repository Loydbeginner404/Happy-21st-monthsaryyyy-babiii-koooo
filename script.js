(function () {
  const cards = document.querySelectorAll(".scratch");
  let doneCount = 0;

  cards.forEach(card => {
    const canvas = card.querySelector("canvas");
    const cctx = canvas.getContext("2d");
    let ready = false, drawing = false, finished = false, last = null, lastCheck = 0;

    function setup() {
      const r = card.getBoundingClientRect();
      const dpr = window.devicePixelRatio || 1;
      canvas.width = r.width * dpr;
      canvas.height = r.height * dpr;
      cctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      const g = cctx.createLinearGradient(0, 0, r.width, r.height);
      g.addColorStop(0, "#d9c9f2");
      g.addColorStop(.5, "#f8cdd6");
      g.addColorStop(1, "#e9c98f");
      cctx.fillStyle = g;
      cctx.fillRect(0, 0, r.width, r.height);
      cctx.fillStyle = "rgba(255,255,255,.55)";
      for (let i = 0; i < 45; i++) {
        cctx.beginPath();
        cctx.arc(rand(0, r.width), rand(0, r.height), rand(1, 2.6), 0, 7);
        cctx.fill();
      }
      cctx.fillStyle = "rgba(106,66,86,.8)";
      cctx.font = "700 22px Quicksand, sans-serif";
      cctx.textAlign = "center";
      cctx.fillText("Scratch me 🤍", r.width / 2, r.height / 2 + 8);
      ready = true;
    }

    const io = new IntersectionObserver(es => {
      if (es[0].isIntersecting && !ready) { setup(); io.disconnect(); }
    }, { threshold: .3 });
    io.observe(card);

    function pos(e) {
      const r = canvas.getBoundingClientRect();
      return { x: e.clientX - r.left, y: e.clientY - r.top };
    }

    function scratchTo(p) {
      cctx.globalCompositeOperation = "destination-out";
      cctx.lineWidth = 38;
      cctx.lineCap = "round";
      cctx.lineJoin = "round";
      cctx.beginPath();
      cctx.moveTo(last.x, last.y);
      cctx.lineTo(p.x, p.y);
      cctx.stroke();
      last = p;
    }

    function check() {
      lastCheck = Date.now();
      if (finished) return;
      const data = cctx.getImageData(0, 0, canvas.width, canvas.height).data;
      let clear = 0, total = 0;
      for (let i = 3; i < data.length; i += 64) {
        total++;
        if (data[i] === 0) clear++;
      }
      if (clear / total > 0.5) finish();
    }

    function finish() {
      finished = true;
      card.classList.add("done");
      const r = card.getBoundingClientRect();
      hearts(r.left + r.width / 2, r.top + r.height / 2, 20);
      confetti(40);
      vibrate([80, 40, 80]);
      doneCount++;
      if (doneCount === cards.length) {
        setTimeout(() => {
          centerBurst(40);
          $("scratchMsg").textContent = "You scratched them all! I love you, babiii 🤍";
        }, 600);
      }
    }

    canvas.addEventListener("pointerdown", e => {
      if (!ready || finished) return;
      drawing = true;
      canvas.setPointerCapture(e.pointerId);
      last = pos(e);
      scratchTo({ x: last.x + 0.01, y: last.y });
    });

    canvas.addEventListener("pointermove", e => {
      if (!drawing || finished) return;
      scratchTo(pos(e));
      if (Date.now() - lastCheck > 250) check();
    });

    const stop = () => { if (drawing) { drawing = false; check(); } };
    canvas.addEventListener("pointerup", stop);
    canvas.addEventListener("pointercancel", stop);
  });
})();

